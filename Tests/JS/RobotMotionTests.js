const assert = require('node:assert/strict');
const {create, MAX_TWEEN_MS} = require('../../Sources/DreameHub/Resources/assets/robot-motion.js');
const base = 1700000000000;
const map = (x, angle, time, frame=1, id=7) => ({robot_position:[x,0,angle],timestamp_ms:base+time,frame_id:frame,map_id:id});
const motion = create();
const first = map(0,350,0), second = map(1000,10,1000,2);
motion.sample(first,0,base); motion.sample(second,1000,base+1000);
assert.deepEqual(motion.pose(1000),[0,0,350]);
const middle=motion.pose(1400);
assert(middle[0]>0&&middle[0]<1000,'Movement must interpolate, not jump');
assert(middle[2]<11||middle[2]>349,'Heading takes shortest path across north');
motion.sample(second,1500,base+1500);
assert.deepEqual(motion.pose(1000+MAX_TWEEN_MS),[1000,0,10],'Duplicate must not restart movement');
for(const t of [2000,6000,1000000]) assert.deepEqual(motion.pose(t),[1000,0,10],'No movement invented after last observation');
assert.deepEqual(second,map(1000,10,1000,2),'Source telemetry not mutated');
motion.sample(map(-1000,180,500,1),2500,base+2500);
assert.deepEqual(motion.pose(2500),[1000,0,10],'Older observation ignored');
motion.sample(map(9999,180,1000,2),2600,base+2600);
assert.deepEqual(motion.pose(2600),[1000,0,10],'Conflicting duplicate frame cannot replace observation');
motion.sample(map(1200,20,3000,3),3000,base+3000); motion.freeze();
assert.deepEqual(motion.pose(3100),[1200,0,20],'Error freezes at latest known endpoint');
motion.sample(map(1300,30,20000,4),20000,base+20000);
assert.deepEqual(motion.pose(20000),[1300,0,30],'Long outage snaps instead of replaying fabricated travel');
motion.sample(map(1400,40,21000,5,8),21000,base+21000);
assert.deepEqual(motion.pose(21000),[1400,0,40],'Map change has no tween');
motion.sample({...map(1500,50,22000,6,8),history_map:true},22000,base+22000);
assert.deepEqual(motion.pose(22000),[1500,0,50],'Historic maps have no live motion');
motion.sample(map(1600,60,23000,7,8),23000,base+23000,true);
assert.deepEqual(motion.pose(23000),[1600,0,60],'Reduced motion respected');
motion.sample(map(9000,60,24000,8,8),24000,base+24000);
assert.deepEqual(motion.pose(24000),[9000,0,60],'Relocalization does not animate through walls');
motion.sample(map(9050,70,25000,9,8),25000,base+40000);
assert.deepEqual(motion.pose(25000),[9050,0,70],'Stale source snaps rather than pretending live motion');
motion.sample({robot_position:null},26000,base+26000);
assert.equal(motion.pose(27000),null,'Missing pose is unknown, not a lingering invented robot');
motion.reset(); assert.equal(motion.pose(0),null);
console.log('PASS: bounded pose interpolation, shortest heading, duplicate/old/stale/map/history handling, freeze, reduced motion, zero extrapolation');
